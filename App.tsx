import React,{lazy,Suspense,useEffect,useRef,useState} from 'react';
import {motion,MotionConfig} from 'framer-motion';
import Navbar from './components/Navbar';
import MobileDock from './components/MobileDock';
import Footer from './components/Footer';
import PasswordGate from './components/PasswordGate';
import ClubhouseHome from './components/ClubhouseHome';
import {readView,ViewState} from './utils/clubNavigation';
export type {ViewState} from './utils/clubNavigation';
const SmashGame=lazy(()=>import('./components/SmashGame'));
const RoundHub=lazy(()=>import('./components/RoundHub'));
const MoreSection=lazy(()=>import('./components/MoreSection'));
const MoneyGameSection=lazy(()=>import('./components/MoneyGameSection'));
const RoundToolsSection=lazy(()=>import('./components/RoundToolsSection'));
const MemberSection=lazy(()=>import('./components/MemberSection'));
const LedgerSection=lazy(()=>import('./components/LedgerSection'));
const WeatherSection=lazy(()=>import('./components/WeatherSection'));
const MapSection=lazy(()=>import('./components/MapSection'));
const RankingSection=lazy(()=>import('./components/RankingSection'));
const GallerySection=lazy(()=>import('./components/GallerySection'));
const NewArchiveSite=lazy(()=>import('./components/NewArchiveSite'));
export default function App(){
 const [hash,setHash]=useState(()=>window.location.hash);
 const mainRef=useRef<HTMLElement>(null);
 const currentView=readView(hash);
 useEffect(()=>{const change=()=>setHash(window.location.hash);window.addEventListener('hashchange',change);return()=>window.removeEventListener('hashchange',change);},[]);
 useEffect(()=>{window.scrollTo({top:0,behavior:'instant'});mainRef.current?.focus({preventScroll:true});},[hash]);
 const navigateTo=(view:ViewState)=>{window.location.hash='/'+view;};
 const back=()=>navigateTo('home');
 const content=()=>{switch(currentView){
 case 'game':return <SmashGame/>;
 case 'rounds':return <RoundHub/>;
 case 'records':return <RoundHub/>;
 case 'more':return <MoreSection/>;
 case 'members':return <MemberSection onBack={back}/>;
 case 'ledger':return <LedgerSection onBack={back}/>;
 case 'weather':return <WeatherSection onBack={()=>navigateTo('rounds')}/>;
 case 'map':return <MapSection onBack={()=>navigateTo('rounds')}/>;
 case 'ranking':return <RankingSection onBack={back}/>;
 case 'gallery':return <GallerySection onBack={()=>navigateTo('more')}/>;
 case 'bets':return <MoneyGameSection onBack={()=>navigateTo('more')}/>;
 case 'tools':return <RoundToolsSection onBack={()=>navigateTo('rounds')}/>;
 default:return <ClubhouseHome/>;
 }};
 return <MotionConfig reducedMotion="user"><PasswordGate>{hash==='#/new-archive'?<Suspense fallback={<p>불러오는 중…</p>}><NewArchiveSite/></Suspense>:<div className="club-app"><a className="skip-link" href="#main-content" onClick={event=>{event.preventDefault();mainRef.current?.focus();}}>본문으로 건너뛰기</a>{currentView!=='game'&&<Navbar currentView={currentView}/>}<main id="main-content" tabIndex={-1} ref={mainRef}><Suspense fallback={<div className="club-container loading-panel" role="status">클럽 기록을 불러오고 있어요…</div>}><motion.div className={['ledger','gallery','bets','tools','map','weather'].includes(currentView)?'legacy-surface':undefined} key={hash} initial={{opacity:0}} animate={{opacity:1}} transition={{duration:.12}}>{content()}</motion.div></Suspense></main>{currentView!=='game'&&<><Footer/><MobileDock currentView={currentView}/></>}</div>}</PasswordGate></MotionConfig>;
}
